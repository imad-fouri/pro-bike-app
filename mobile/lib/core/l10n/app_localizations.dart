  /// `l10n_key` this build does not know would take the app down on open.
  ///
  /// Returning the key keeps the failure visible and harmless.
  String get(String key) => _lookup(key) ?? key;

  /// Like [get], but substitutes `{name}` placeholders from [params].
  ///
  /// Interpolation is done here rather than at each call site so RTL text is
  /// never assembled by hand: hand-rolled `String.replace` across three locales
  /// is exactly how a bidirectional string gets its punctuation or its argument
  /// order corrupted. Placeholders are matched literally, so an argument
  /// containing `{` or `}` is inserted verbatim and cannot be re-expanded.
  String getWith(String key, Map<String, String> params) {
    var text = _lookup(key) ?? key;
    params.forEach((name, value) {
      text = text.replaceAll('{$name}', value);
    });
    return text;
  }

  /// The raw template for a key, or null when this build does not know it.
  ///
  /// Callers that render server-driven keys should use this to detect an
  /// unknown key and fall back deliberately, rather than rendering the key
  /// itself as though it were copy.
  String? template(String key) => _lookup(key);

  /// Whether this build has a translation for [key] in the active locale.
  bool has(String key) => _lookup(key) != null;

  String? _lookup(String key) =>
      _values[locale.languageCode]?[key] ?? _values['en']?[key];

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations)!;
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();
  @override
  bool isSupported(Locale locale) =>
      ['en', 'fr', 'ar'].contains(locale.languageCode);
  @override
  Future<AppLocalizations> load(Locale locale) async =>
      AppLocalizations(locale);
  @override
  bool shouldReload(covariant LocalizationsDelegate<AppLocalizations> old) =>
      false;
}

extension L10nX on BuildContext {
  AppLocalizations get l10n => AppLocalizations.of(this);
}
